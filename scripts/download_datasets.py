"""Download the external dataset used by the trained-LM experiment.

    python scripts/download_datasets.py

Tiny Shakespeare (1.1 MB, character-level text) is saved to
training/data/tinyshakespeare.txt, where training/train_lm.py reads it;
train_lm.py itself does the preprocessing (character vocabulary and a 90/10
train/validation split). The XLA rewrite study needs no external data: its 36
workloads are generated by benchmarks/gpu_benchmark.py (BUILDERS) and its raw
measurements are in docs/results/.
"""

import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
URL = "https://raw.githubusercontent.com/karpathy/char-rnn/master/data/tinyshakespeare/input.txt"
DEST = ROOT / "training" / "data" / "tinyshakespeare.txt"


def main():
    if DEST.exists():
        print("already present:", DEST)
        return
    DEST.parent.mkdir(parents=True, exist_ok=True)
    urllib.request.urlretrieve(URL, DEST)
    print(f"saved {DEST} ({DEST.stat().st_size / 1e6:.1f} MB)")


if __name__ == "__main__":
    main()
