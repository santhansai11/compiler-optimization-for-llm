"""Build every table of the XLA rewrite study from its saved raw data.

    python tools/make_xla_tables.py [docs/results/xla_rewrite_study.json]

Writes ``<stem>_tables.md`` (all tables, units in every header) and
``<stem>_samples.csv`` (one row per timing sample: workload, policy, round,
microseconds) next to the input file.
"""

import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT = ROOT / "docs" / "results" / "xla_rewrite_study.json"
POLICY_LABELS = {"all_safe": "All-safe", "guided": "Guided", "random_same": "Random (same count)",
                 "fixed_no_cse": "Fixed rule (no CSE)"}


def table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


def f(x, digits=3):
    return "–" if x is None or x != x else f"{x:.{digits}f}"


def environment(env):
    pk = env.get("packages", {})
    git = env.get("git", {})
    rows = [("CPU", env.get("cpu")), ("Cores (physical / logical)", f"{env.get('physical_cores')} / {env.get('logical_cores')}"),
            ("OS", f"{env.get('os')} ({env.get('os_version')})"), ("Python", env.get("python")),
            ("jax / jaxlib", f"{pk.get('jax')} / {pk.get('jaxlib')}"), ("torch", pk.get("torch")),
            ("numpy / scipy", f"{pk.get('numpy')} / {pk.get('scipy')}"),
            ("XLA devices", ", ".join(env.get("jax_devices") or [])),
            ("Thread settings", ", ".join(f"{k}={v}" for k, v in env.get("thread_env", {}).items() if v) or "defaults"),
            ("Git commit", f"{git.get('commit')} ({'dirty' if git.get('dirty') else 'clean'}, tag {git.get('tag')})")]
    return table(["Item", "Value"], rows)


def main():
    path = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT
    res = json.loads(path.read_text())
    cfg, pm, pol = res["config"], res["pair_model"], res["policies"]
    s = pol["summary"]
    out = [f"# XLA rewrite study — tables\n\nGenerated by `tools/make_xla_tables.py` from `{path.name}`. "
           f"Latencies in microseconds (µs); speedup = baseline / variant (> 1 is faster).\n",
           f"{len(res['workloads'])} workloads, {cfg['rounds']} paired timing rounds per variant "
           f"(variant order shuffled each round), {len(res['raw']['graphs'])} XLA-timed graphs, "
           f"{len(res['raw']['transitions'])} measured rewrite pairs.\n",
           "## Environment\n", environment(res["environment"])]

    out.append("\n## Prediction quality on held-out architectures (labels: XLA latency)\n")
    rows = [(a, q["graphs"], q["pairs"], f(q["latency_mae_us"], 1), f(q["latency_mape_pct"], 1), f(q["latency_spearman"], 2),
             f(q["pair_speedup_mae"]), f(q["pair_spearman"], 2), f(q["pair_sign_agreement_pct"], 1),
             f"{f(q['pair_spearman_near_1'], 2)} (n={q['pairs_near_threshold']})")
            for a, q in pm["leave_one_architecture_out"].items()]
    m = pm["mean"]
    rows.append(("**mean**", "", "", f(m["latency_mae_us"], 1), f(m["latency_mape_pct"], 1), f(m["latency_spearman"], 2),
                 f(m["pair_speedup_mae"]), f(m["pair_spearman"], 2), f(m["pair_sign_agreement_pct"], 1),
                 f(m["pair_spearman_near_1"], 2)))
    out.append(table(["Held-out architecture", "Graphs", "Pairs", "Latency MAE (µs)", "Latency MAPE (%)", "Latency ρ",
                      "Pair speedup MAE", "Pair ρ", "Pair sign agree (%)", "Pair ρ, pred. within ±5%"], rows))

    out.append(f"\n## Pair decisions vs measured outcome (pooled over folds; neutral = |speedup − 1| < {cfg['noise_band']})\n")
    rows = []
    for key, rule in (("confusion", "guided rule (threshold, or tie and fewer nodes)"),
                      ("confusion_threshold_only", "threshold only")):
        for th in map(str, cfg["thresholds"]):
            tot = {}
            for q in pm["leave_one_architecture_out"].values():
                for k, v in q[key][th].items():
                    if k != "correct_decisions_pct":
                        tot[k] = tot.get(k, 0) + v
            rows.append((rule, th, tot["accepted_beneficial"], tot["accepted_neutral"], tot["accepted_harmful"],
                         tot["rejected_beneficial"], tot["rejected_neutral"], tot["rejected_harmful"]))
    out.append(table(["Decision rule", "Accept threshold", "Accepted: beneficial", "Accepted: neutral", "Accepted: harmful (wrong)",
                      "Rejected: beneficial (missed)", "Rejected: neutral", "Rejected: harmful"], rows))

    out.append("\n## Policies vs no rewriting (per-workload paired speedup; verdict from 95% bootstrap CI)\n")
    rows = [(POLICY_LABELS[p], f(v["suite_median_speedup"]), f"[{f(v['suite_median_ci95'][0])}, {f(v['suite_median_ci95'][1])}]",
             f(v["suite_geomean_speedup"]), v["workloads_faster"], v["workloads_slower"], v["workloads_indistinguishable"],
             v["workloads_significant_holm"], v["workloads_hlo_identical_to_none"])
            for p, v in s.items() if p in POLICY_LABELS]
    out.append(table(["Policy", "Suite median speedup", "95% CI", "Geomean", "Faster", "Slower", "Indistinguishable",
                      "Wilcoxon sig. (Holm)", "Same optimised HLO as original"], rows))

    g = s["guided_vs_all_safe"]
    out.append("\n## Guided vs all-safe (paired, per workload)\n")
    out.append(table(["Median ratio (all-safe / guided)", "95% CI", "Wilcoxon p (across workloads)", "Guided faster",
                      "Guided slower", "Indistinguishable", "Identical optimised HLO"],
                     [(f(g["median_ratio"], 4), f"[{f(g['median_ratio_ci95'][0], 4)}, {f(g['median_ratio_ci95'][1], 4)}]",
                       f(g["wilcoxon_p_across_workloads"], 4), g["workloads_guided_faster"], g["workloads_guided_slower"],
                       g["workloads_indistinguishable"], g["workloads_same_hlo"])]))
    d = s["guided_decisions"]
    out.append(f"\nGuided search scored {d.get('candidates_scored')} candidates; {d.get('no_estimate')} had no usable "
               f"estimate. Mean rewrites applied: guided {f(s['guided_rewrites_applied_mean'], 1)}, "
               f"all-safe {f(s['all_safe_rewrites_applied_mean'], 1)}. All outputs match the original: "
               f"{s['all_outputs_match']}.\n")

    out.append("\n## Does a rewrite change the program XLA compiles?\n")
    rows = [(r, v["pairs"], v["hlo_changed"], f(v["median_speedup_all"]), f(v["median_speedup_hlo_changed"]),
             f(v["median_speedup_hlo_unchanged"]))
            for r, v in res["rules"].items()]
    out.append(table(["Rule", "Measured pairs", "Optimised HLO changed", "Median speedup (all)",
                      "Median speedup (HLO changed)", "Median speedup (HLO unchanged)"], rows))
    out.append(f"\nBefore/after HLO and canonical diffs of the most positive, most negative and most neutral "
               f"instance of each rule: `{path.stem}_hlo/rules/`.\n")

    out.append("\n## Per-workload speedup vs no rewriting (median [95% CI])\n")
    rows = []
    for r in pol["rows"]:
        cells = [f"{f(v['median_speedup'])} [{f(v['ci95'][0])}, {f(v['ci95'][1])}]" for v in r["vs_none"].values()]
        rows.append([r["workload"], f(sum(r["samples_us"]["none"]) / len(r["samples_us"]["none"]), 1)] + cells)
    out.append(table(["Workload", "Original mean (µs)"] + [POLICY_LABELS[p] for p in pol["rows"][0]["vs_none"]], rows))

    md = path.with_name(path.stem + "_tables.md")
    md.write_text("\n".join(out))
    csv_path = path.with_name(path.stem + "_samples.csv")
    with csv_path.open("w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["workload", "policy", "round", "latency_us", "inner_calls_per_sample"])
        for r in pol["rows"]:
            for p, samples in r["samples_us"].items():
                for i, us in enumerate(samples):
                    w.writerow([r["workload"], p, i, f"{us:.3f}", r["inner_calls_per_sample"]])
    print("wrote", md, "and", csv_path)


if __name__ == "__main__":
    main()
